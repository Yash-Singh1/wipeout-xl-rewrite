#!/usr/bin/env python3
"""The second player's game (platform/second/): the header that gives its copy of the game its own names.

    second_game.py names NM PREFIX OUT.h FIRST...
    second_game.py check NM PREFIX STAMP FIRST... -- SECOND...

names: every global the first game's libraries and objects (FIRST) define, functions and variables, is renamed
NAME__p2 in the second's sources, which are compiled again with this header in front: the program then holds two
games, each with its own state, that share nothing but the platform's libraries (SDL, Dear ImGui). The header is
rewritten only when the names change, so the second game is compiled again only then.

check: the second game's objects (SECOND) use none of the first game's globals (it would share them), and the
stamp file is written.

PREFIX is what the object files put in front of C names: "_" on Apple's, else nothing ("-").
"""
import re
import subprocess
import sys

# the entry point and the C library's process-wide calls are the second game's own (platform/second/entry.c)
SPECIAL = {
    'main': 'PortSecondGameMainEntry',
    'exit': 'PortSecondExit',
    'atexit': 'PortSecondAtExit',
    'getenv': 'PortSecondGetenv',
    'malloc': 'PortSecondMalloc',
    'calloc': 'PortSecondCalloc',
    'realloc': 'PortSecondRealloc',
    'free': 'PortSecondFree',
    'SDL_getenv': 'PortSecondSDLGetenv',
}
# what each platform's start-up code defines around main
NOT_RENAMED = {'main', 'SDL_main', 'WinMain', 'wWinMain', 'SDL_RunApp'}


def symbols(nm, path, prefix, undefined):
    """The C names an object or library defines (or, undefined, uses without defining)."""
    out = subprocess.run([nm, '-g', path], check=True, capture_output=True, text=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if not parts or parts[-1].endswith(':'):
            continue
        kind = parts[-2] if len(parts) >= 2 else ''
        if undefined != (kind == 'U'):
            continue
        if not undefined and (len(parts) < 3 or kind in ('u', 'w', 'v', 'W', 'V', 'I', 'i')):
            continue
        name = parts[-1]
        if prefix:
            if not name.startswith(prefix):
                continue
            name = name[len(prefix):]
        if re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', name):
            names.add(name)
    return names


def check(nm, prefix, stamp, paths):
    split = paths.index('--')
    first, second = paths[:split], paths[split + 1:]
    defined = set()
    for path in first:
        defined |= symbols(nm, path, prefix, False)
    used = set()
    for path in second:
        used |= symbols(nm, path, prefix, True)
    shared = sorted((used & defined) - NOT_RENAMED)
    if shared:
        sys.exit('second_game.py: the second player\'s game uses the first\'s %s' % ', '.join(shared[:20]))
    with open(stamp, 'w') as f:
        f.write('ok\n')


def main():
    command, nm, prefix, out, inputs = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5:]
    prefix = '' if prefix == '-' else prefix
    if command == 'check':
        check(nm, prefix, out, inputs)
        return
    names = set()
    for path in inputs:
        names |= symbols(nm, path, prefix, False)
    names -= NOT_RENAMED
    names -= set(SPECIAL)
    lines = ['/* Generated by tools/second_game.py: the second player\'s game\'s own names (platform/second/). */',
             '#ifndef PORT_SECOND_GAME_NAMES_H', '#define PORT_SECOND_GAME_NAMES_H', '']
    lines += ['#define %s %s' % item for item in sorted(SPECIAL.items())]
    lines += ['#define %s %s__p2' % (name, name) for name in sorted(names)]
    lines += ['', '#include "second/sections.h"', '', '#endif', '']
    text = '\n'.join(lines)
    try:
        with open(out) as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(out, 'w') as f:
        f.write(text)


if __name__ == '__main__':
    main()
