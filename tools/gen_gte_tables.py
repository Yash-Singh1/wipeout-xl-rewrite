#!/usr/bin/env python3
"""Generates platform/psx/gte_tables.c: the read-only tables of the PsyQ
library math routines (rsin/rcos, SquareRoot0, ratan2), copied from the
user's retail executable (SCUS_943.51) so the results are bit-exact.

usage: gen_gte_tables.py [path/to/SCUS_943.51]"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_EXE = ROOT.parent / 'wipeout-xl' / 'extracted' / 'SCUS_943.51'
# The library's tables: sine (0x80090080, 4096 halfwords), square root
# (0x80092094, 192 halfwords) and arctangent (0x800926B0, 1025 halfwords).
REGION = (0x80090080, 0x80092EB4)


def main():
    exe = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_EXE
    data = exe.read_bytes()
    if data[:8] != b'PS-X EXE':
        raise SystemExit('%s is not a PS-X EXE' % exe)
    load = struct.unpack_from('<I', data, 0x18)[0]
    start, end = REGION
    blob = data[0x800 + start - load:0x800 + end - load]
    lines = ['/* Generated by tools/gen_gte_tables.py from the retail executable: do not edit. */',
             '#include "gte.h"', '',
             'const unsigned int gteTableBase = 0x%08X;' % start,
             'const unsigned int gteTableEnd = 0x%08X;' % end,
             'const unsigned char gteTables[%d] = {' % len(blob)]
    for i in range(0, len(blob), 16):
        lines.append('    ' + ', '.join('0x%02x' % b for b in blob[i:i + 16]) + ',')
    lines.append('};')
    (ROOT / 'platform' / 'psx' / 'gte_tables.c').write_text('\n'.join(lines) + '\n')
    print('%d bytes from %s' % (len(blob), exe))


if __name__ == '__main__':
    main()
