void ShowCredits(int y)
{
    int group;
    int index;
    int style;

    y -= 3000;
    group = 0;
    style = 1;
    do {
        if ((u_int)(y + 9) < 273) {
            CentreText(creditEntries[group].title, 230, y, 8, 0);
        }
        y += 16;
        for (index = 0; index < creditEntries[group].count; index++) {
            if ((u_int)(y + 9) < 273) {
                CentreText(creditEntries[group].lines[index], 230, y, 8, style);
            }
            y += 12;
        }
        y += 32;
        group++;
    } while (group < 35);
}
