#ifndef PORT_WIDEN_H
#define PORT_WIDEN_H

/* Port: conversion between the PlayStation's 32-bit file layout of the game's records and the native layout.

   The game reads some file contents straight into C structs, or walks a file buffer as an array of
   structs. Structs that hold pointers are larger on a 64-bit target, so the loaders convert the bytes
   right after reading them. The tables in port_records.h (generated by tools/genlayouts.py) describe
   both layouts; docs/RECORDS.md lists the record types and where they are read and written. */

#include "port_records.h"
#include "functions.h"

/* A compile-time check that also works in C89: a negative array size is an error. The generated
   tables use it to check the native column against the compiler, and the files the game writes use it
   to keep their record layout. */
#define PORT_ASSERT_JOIN2(a, b) a##b
#define PORT_ASSERT_JOIN(a, b) PORT_ASSERT_JOIN2(a, b)
#define PORT_ASSERT(condition) typedef char PORT_ASSERT_JOIN(PortAssertion, __LINE__)[(condition) ? 1 : -1]

/* Converts count file-layout records at source to native records at destination (which must hold
   count * table->nativeSize bytes and must not overlap source). Scalars are copied byte for byte and
   padding is zeroed. Each 4-byte pointer slot goes into the first 4 bytes of the 8-byte native slot
   and the rest of the slot is zero, so that an int member of a union with the pointer reads the file
   value. (The game runs on little-endian hosts.) */
void PortWidenRecords(const PortRecordTable *table, const void *source, int count, void *destination);

/* The inverse, for files the game writes: keeps the first 4 bytes of each native pointer slot. For
   records that were widened from a file this restores the file bytes exactly. destination needs
   count * table->fileSize bytes. */
void PortNarrowRecords(const PortRecordTable *table, const void *source, int count, void *destination);

/* Widens the count records at source (a block of heap) into a new block of the same heap, with the
   32 spare bytes the loaders allocate, and frees source. Returns the new block. */
void *PortWidenHeapRecords(HeapBlock *heap, const PortRecordTable *table, char *source, int count);

/* A PRM image holds, for each object, an Object record, a Skeleton record, the vertices and the
   primitives of several types. PortWidenPrm walks a file image the way LoadPrmCommon does and widens
   only the Object and Skeleton records; vertices and primitives are copied verbatim. Native Object
   records start on PORT_PRM_ALIGNMENT bytes (counted from the start of the image), so the walk pads
   the gap after the primitives of the previous object; LoadPrmCommon skips it with PortAlignPrm.
   Returns the length of the widened image (without trailing padding). destination may be null to
   only measure; otherwise it needs that many bytes and is zeroed first. Bytes after a record the
   walk cannot parse are copied unchanged. */
#define PORT_PRM_ALIGNMENT 8
int PortWidenPrm(const char *file, int length, char *destination);

/* Widens a PRM file image read into a block of heap: allocates the widened image, frees file and
   returns the image; *length becomes the widened length. */
char *PortWidenPrmImage(HeapBlock *heap, char *file, int *length);

/* Length of the widened image PortWidenPrmImage built last (the weapon code copies whole images). */
extern int portLastPrmImageLength;

/* The start of the next Object record at or after the pointer p of the image starting at start. */
char *PortAlignPrm(char *start, char *p);

#endif
